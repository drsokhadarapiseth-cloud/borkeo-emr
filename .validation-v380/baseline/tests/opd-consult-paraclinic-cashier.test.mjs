import assert from 'node:assert/strict';
import test from 'node:test';
import { readFileSync } from 'node:fs';
import { createEmrServer } from '../server/server.mjs';
import { opdLocalDate } from '../server/opd-queue.mjs';

test('OPD doctor order form exposes paid/free choices and the two handoff actions',()=>{
  const form=readFileSync(new URL('../public/paraclinic.js',import.meta.url),'utf8');
  const cashier=readFileSync(new URL('../public/billing.js',import.meta.url),'utf8');
  assert.match(form,/name="chargeMode" value="PAID"/);
  assert.match(form,/name="chargeMode" value="FREE"/);
  assert.match(form,/data-route="DIRECT"/);
  assert.match(form,/data-route="NURSE"/);
  assert.match(form,/បញ្ជូនទៅបញ្ជរបង់ប្រាក់/);
  assert.match(form,/Send to Nurse/);
  assert.doesNotMatch(form,/name="handoffMode"/);
  assert.match(form,/Direct to Cashier and then Lab\/Imaging is the usual route/);
  assert.match(cashier,/paraclinicPaymentPending/);
});

test('OPD post-consult paid paraclinic orders wait for cashier while free orders go directly to the department', async () => {
  const port=32430;
  const origin=`http://127.0.0.1:${port}`;
  const app=createEmrServer({demoMode:true,host:'127.0.0.1',port,appOrigin:origin,databasePath:':memory:',autoDatabase:false,nodeEnv:'test'});
  await new Promise(resolve=>app.server.listen(port,'127.0.0.1',resolve));
  try {
    const login=async username=>{
      const response=await fetch(origin+'/api/auth/login',{method:'POST',headers:{Origin:origin,'Content-Type':'application/json'},body:JSON.stringify({username})});
      assert.equal(response.status,200,username);
      const cookie=response.headers.get('set-cookie').split(';')[0];
      const me=await (await fetch(origin+'/api/auth/me',{headers:{Cookie:cookie}})).json();
      return {Cookie:cookie,Origin:origin,'Content-Type':'application/json','X-CSRF-Token':me.csrfToken};
    };
    const registration=await login('registration');
    const triage=await login('triage');
    const doctor=await login('doctor_opd');
    const clerk=await login('clerk');
    const lab=await login('lab');
    const imaging=await login('imaging');
    const nurse=await login('nurse_opd');
    const key='case:OPD-CONSULT-PARA-1';
    const today=opdLocalDate();
    const registrationSummary={caseNumber:'OPD-CONSULT-PARA-1',healthId:'PARA-CONSULT-1',firstName:'Consult',lastName:'Patient',fullName:'Consult Patient',sex:'ប្រុស',age:'35',dateOfBirth:'',phone:'',equityCard:'',paymentType:'CASH',departmentCode:'',departmentNameKh:'',departmentNameEn:'',serviceMode:'',entryDate:today,dischargeDate:''};
    let response=await fetch(origin+'/api/patient-record',{method:'PUT',headers:registration,body:JSON.stringify({patientKey:key,summary:registrationSummary,data:{'scope:registration:id:emr_pmrs_case_new':true}})});
    assert.equal(response.status,200,await response.text());
    let patient=(await (await fetch(origin+`/api/patient-record?patientKey=${encodeURIComponent(key)}`,{headers:registration})).json()).patient;
    const opdSummary={...registrationSummary,departmentCode:'opd',departmentNameKh:'ពិគ្រោះក្រៅ',departmentNameEn:'OPD',serviceMode:'opd'};
    response=await fetch(origin+'/api/patient-record',{method:'PUT',headers:triage,body:JSON.stringify({patientKey:key,summary:opdSummary,data:{'scope:triage:id:p2_temp':'37.1','scope:triage:id:p2_pulse':'80','scope:triage:id:p2_resp':'18','scope:triage:id:p2_spo2':'98','scope:triage:id:p2_weight':'65','scope:triage:id:p2_height':'170'},expectedVersion:patient.version})});
    assert.equal(response.status,200,await response.text());
    patient=(await (await fetch(origin+`/api/patient-record?patientKey=${encodeURIComponent(key)}`,{headers:registration})).json()).patient;

    let cashierBill=(await (await fetch(origin+`/api/finance/patient?patientKey=${encodeURIComponent(key)}`,{headers:clerk})).json()).bill;
    assert.ok(cashierBill.summary.KHR.balance>0,'OPD consultation charge is outstanding');
    const preConsultQueue=(await (await fetch(origin+`/api/finance/patients?view=queue&q=${encodeURIComponent('OPD-CONSULT-PARA-1')}`,{headers:clerk})).json()).patients;
    assert.equal(preConsultQueue.length,1,'Triage sends the OPD consultation fee to Cashier before the patient meets the doctor');
    patient=(await (await fetch(origin+`/api/patient-record?patientKey=${encodeURIComponent(key)}`,{headers:doctor})).json()).patient;
    response=await fetch(origin+'/api/patient-record',{method:'PUT',headers:doctor,body:JSON.stringify({patientKey:key,summary:opdSummary,data:{'scope:medical:id:opd_note':'Should not save before payment'},expectedVersion:patient.version})});
    assert.equal(response.status,409,'the OPD clinical form stays locked until the consultation invoice is settled');
    response=await fetch(origin+'/api/finance/payments',{method:'POST',headers:clerk,body:JSON.stringify({patientKey:key,invoiceId:cashierBill.invoice.id,source:'CASH',amount:cashierBill.summary.KHR.balance,currency:'KHR'})});
    assert.equal(response.status,201,await response.text());
    patient=(await (await fetch(origin+`/api/patient-record?patientKey=${encodeURIComponent(key)}`,{headers:doctor})).json()).patient;
    assert.equal(patient.workflowStage,'DOCTOR_READY','Cashier payment unlocks the OPD consultation');
    response=await fetch(origin+'/api/patient-record',{method:'PUT',headers:doctor,body:JSON.stringify({patientKey:key,summary:opdSummary,data:{'scope:medical:id:opd_note':'OPD consultation completed'},expectedVersion:patient.version})});
    const consultSaved=await response.json();
    assert.equal(response.status,200,JSON.stringify(consultSaved));
    patient=consultSaved.patient;
    assert.ok(patient.data['system:opdConsultedAt'],'saving the OPD consultation marks the consult ready for follow-up tests');
    const afterConsultQueue=(await (await fetch(origin+`/api/finance/patients?view=queue&q=${encodeURIComponent('OPD-CONSULT-PARA-1')}`,{headers:clerk})).json()).patients;
    assert.equal(afterConsultQueue.length,0,'settled consultation invoices are removed from Cashier queue');

    const makeOrder=(modality,chargeMode,requestData,options={})=>fetch(origin+'/api/paraclinic/orders',{method:'POST',headers:doctor,body:JSON.stringify({patientKey:key,modality,priority:'ROUTINE',chargeMode,handoffMode:options.handoffMode||'DIRECT',request:requestData})});
    const labResponse=await makeOrder('LAB','PAID',{clinicalInfo:'Post-consult check',items:[{code:'CBC',urgent:false}]});
    const labCreated=await labResponse.json();
    assert.equal(labResponse.status,201,JSON.stringify(labCreated));
    assert.equal(labCreated.order.status,'PAYMENT_PENDING');
    assert.equal(labCreated.cashierPaymentRequired,true);
    const imagingResponse=await makeOrder('XRAY','PAID',{examination:'Chest',projection:'PA',clinicalIndication:'Cough'});
    const imagingCreated=await imagingResponse.json();
    assert.equal(imagingResponse.status,201,JSON.stringify(imagingCreated));
    assert.equal(imagingCreated.order.status,'PAYMENT_PENDING');
    const twoTestResponse=await makeOrder('LAB','PAID',{clinicalInfo:'Two-test order',items:[{code:'CREAT',urgent:false},{code:'CRP',urgent:false}]});
    const twoTestCreated=await twoTestResponse.json();
    assert.equal(twoTestResponse.status,201,JSON.stringify(twoTestCreated));
    const threeTestResponse=await makeOrder('LAB','PAID',{clinicalInfo:'Three-test order',items:[{code:'ALT',urgent:false},{code:'AST',urgent:false},{code:'UREA',urgent:false}]});
    const threeTestCreated=await threeTestResponse.json();
    assert.equal(threeTestResponse.status,201,JSON.stringify(threeTestCreated));

    let patientSearch=(await (await fetch(origin+`/api/finance/patients?view=queue&q=${encodeURIComponent('OPD-CONSULT-PARA-1')}`,{headers:clerk})).json()).patients;
    assert.equal(patientSearch[0]?.paraclinicPaymentPending,true,'Cashier list highlights this patient');
    let labList=(await (await fetch(origin+'/api/paraclinic/orders?modality=LAB',{headers:lab})).json()).orders;
    assert.ok(!labList.some(item=>item.id===labCreated.order.id),'Lab cannot view an unpaid request');
    let imagingList=(await (await fetch(origin+'/api/paraclinic/orders',{headers:imaging})).json()).orders;
    assert.ok(!imagingList.some(item=>item.id===imagingCreated.order.id),'Imaging cannot view an unpaid request');
    response=await fetch(origin+`/api/paraclinic/orders/${labCreated.order.id}`,{method:'PATCH',headers:lab,body:JSON.stringify({status:'PROCESSING'})});
    assert.equal(response.status,400,'department cannot start a pending order by changing its status');

    cashierBill=(await (await fetch(origin+`/api/finance/patient?patientKey=${encodeURIComponent(key)}`,{headers:clerk})).json()).bill;
    assert.ok(cashierBill.charges.some(charge=>charge.sourceKey?.startsWith(`PARACLINIC:${labCreated.order.id}:`)&&charge.serviceCode==='CBC'));
    assert.ok(cashierBill.charges.some(charge=>charge.sourceKey?.startsWith(`PARACLINIC:${imagingCreated.order.id}:`)&&charge.serviceCode==='XRAY_SINGLE_PLATE'));
    const twoTestCharges=cashierBill.charges.filter(charge=>charge.sourceKey?.startsWith(`PARACLINIC:${twoTestCreated.order.id}:`));
    const threeTestCharges=cashierBill.charges.filter(charge=>charge.sourceKey?.startsWith(`PARACLINIC:${threeTestCreated.order.id}:`));
    assert.equal(twoTestCharges.length,2,'two doctor-selected laboratory tests produce exactly two invoice lines');
    assert.equal(threeTestCharges.length,3,'three doctor-selected laboratory tests produce exactly three invoice lines');
    assert.ok([...twoTestCharges,...threeTestCharges].every(charge=>charge.quantity===1),'each doctor-selected test is billed once');
    response=await fetch(origin+'/api/finance/payments',{method:'POST',headers:clerk,body:JSON.stringify({patientKey:key,invoiceId:cashierBill.invoice.id,source:'CASH',amount:cashierBill.summary.KHR.balance,currency:'KHR'})});
    assert.equal(response.status,201,await response.text());
    const afterNewInvoicePayment=(await(await fetch(origin+`/api/patient-record?patientKey=${encodeURIComponent(key)}`,{headers:doctor})).json()).patient;
    assert.equal(afterNewInvoicePayment.workflowStage,'DOCTOR_READY','settling a later test invoice does not replace the saved OPD consultation payment');
    const followupClinicalSave=await fetch(origin+'/api/patient-record',{method:'PUT',headers:doctor,body:JSON.stringify({patientKey:key,summary:opdSummary,data:{'scope:medical:id:opd_note':'Follow-up after separate test invoice'},expectedVersion:afterNewInvoicePayment.version,editorScope:'medical'})});
    assert.equal(followupClinicalSave.status,200,await followupClinicalSave.text());
    const savedOrders=(await (await fetch(origin+`/api/paraclinic/orders?patientKey=${encodeURIComponent(key)}`,{headers:doctor})).json()).orders;
    assert.equal(savedOrders.find(item=>item.id===labCreated.order.id)?.status,'ORDERED');
    assert.equal(savedOrders.find(item=>item.id===imagingCreated.order.id)?.status,'ORDERED');
    labList=(await (await fetch(origin+'/api/paraclinic/orders?modality=LAB',{headers:lab})).json()).orders;
    imagingList=(await (await fetch(origin+'/api/paraclinic/orders',{headers:imaging})).json()).orders;
    assert.ok(labList.some(item=>item.id===labCreated.order.id),'Lab sees the order after cashier settlement');
    assert.ok(imagingList.some(item=>item.id===imagingCreated.order.id),'Imaging sees the order after cashier settlement');

    const imagingRelease=await fetch(origin+`/api/paraclinic/orders/${imagingCreated.order.id}`,{method:'PATCH',headers:imaging,body:JSON.stringify({status:'PROCESSING',performed:true,release:true,result:{findings:'No acute chest finding.',conclusion:'Normal chest imaging.',recommendation:''}})});
    const imagingReleased=await imagingRelease.json();
    assert.equal(imagingRelease.status,200,JSON.stringify(imagingReleased));
    assert.equal(imagingReleased.investigationText,'','imaging findings stay in the separate report');
    assert.match(imagingReleased.order.result.conclusion,/Normal chest imaging/);

    const releasedResult=await fetch(origin+`/api/paraclinic/orders/${labCreated.order.id}`,{method:'PATCH',headers:lab,body:JSON.stringify({status:'PROCESSING',release:true,result:{items:[{code:'HGB',value:13.2,unit:'g/dL'}]}})});
    const releasedBody=await releasedResult.json();
    assert.equal(releasedResult.status,200,JSON.stringify(releasedBody));
    assert.equal(releasedBody.investigationText,'','results remain in their report, not in the request field');
    assert.equal(releasedBody.order.result.items.find(item=>item.code==='HGB').value,13.2);
    const savedRecord=(await(await fetch(origin+`/api/patient-record?patientKey=${encodeURIComponent(key)}`,{headers:doctor})).json()).patient;
    assert.match(savedRecord.data['scope:medical:id:inv_list'],/Complete Blood Count \/ FBC \(CBC\)/);
    assert.doesNotMatch(savedRecord.data['scope:medical:id:inv_list'],/13\.2 g\/dL|Laboratory result/,'lab results are separate from requests');
    assert.doesNotMatch(savedRecord.data['scope:medical:id:inv_list'],/Normal chest imaging/,'imaging results are separate from requests');
    assert.equal((await(await fetch(origin+`/api/finance/patients?view=queue&q=${encodeURIComponent('OPD-CONSULT-PARA-1')}`,{headers:clerk})).json()).patients.length,0,'settled invoices leave the Cashier queue');

    const priorInvoiceCount=(await (await fetch(origin+`/api/finance/patient?patientKey=${encodeURIComponent(key)}`,{headers:clerk})).json()).invoices.length;
    const freeResponse=await makeOrder('LAB','FREE',{clinicalInfo:'No-charge follow-up',items:[{code:'GLU',urgent:false}]});
    const freeCreated=await freeResponse.json();
    assert.equal(freeResponse.status,201,JSON.stringify(freeCreated));
    assert.equal(freeCreated.order.status,'ORDERED');
    assert.equal(freeCreated.order.request.chargeMode,'FREE');
    const finalBill=(await (await fetch(origin+`/api/finance/patient?patientKey=${encodeURIComponent(key)}`,{headers:clerk})).json());
    assert.equal(finalBill.invoices.length,priorInvoiceCount,'free request does not create a new invoice');
    assert.ok(!finalBill.bill.charges.some(charge=>charge.sourceKey?.startsWith(`PARACLINIC:${freeCreated.order.id}:`)),'free request adds no cashier charge');

    const nurseIdentity=await(await fetch(origin+'/api/auth/me',{headers:{Cookie:nurse.Cookie}})).json();
    assert.equal(nurseIdentity.user?.activeRole,'NURSE');
    assert.equal(nurseIdentity.user?.activeWard?.code,'opd');
    const handoffPage=await fetch(origin+'/opd-paraclinic-nurse',{headers:{Cookie:nurse.Cookie},redirect:'manual'});
    assert.equal(handoffPage.status,200,'OPD nurse can open the handoff workspace');
    const nurseLabResponse=await makeOrder('LAB','PAID',{clinicalInfo:'Nurse handoff test',items:[{code:'HBA1C',urgent:false}]},{handoffMode:'NURSE'});
    const nurseLab=await nurseLabResponse.json();
    assert.equal(nurseLabResponse.status,201,JSON.stringify(nurseLab));
    assert.equal(nurseLab.order.status,'PAYMENT_PENDING','paid nurse-routed requests are sent to Cashier before the nurse collects');
    assert.equal(nurseLab.order.request.opdHandoff.stage,'WAITING_NURSE');
    patientSearch=(await(await fetch(origin+`/api/finance/patients?view=queue&q=${encodeURIComponent('OPD-CONSULT-PARA-1')}`,{headers:clerk})).json()).patients;
    assert.equal(patientSearch[0]?.paraclinicPaymentPending,true,'Cashier sees nurse-routed charges before sample collection');
    labList=(await(await fetch(origin+'/api/paraclinic/orders?modality=LAB',{headers:lab})).json()).orders;
    assert.ok(!labList.some(item=>item.id===nurseLab.order.id),'Laboratory cannot see the order before the nurse sends it');
    let nurseQueue=(await(await fetch(origin+'/api/opd/nurse-paraclinic-orders',{headers:nurse})).json()).orders;
    assert.ok(!nurseQueue.some(item=>item.order.id===nurseLab.order.id),'nurse sees paid orders only after Cashier clears them');
    const nurseAction=async(orderId,action)=>fetch(origin+`/api/opd/nurse-paraclinic-orders/${orderId}/action`,{method:'POST',headers:nurse,body:JSON.stringify({action})});
    cashierBill=(await(await fetch(origin+`/api/finance/patient?patientKey=${encodeURIComponent(key)}`,{headers:clerk})).json()).bill;
    response=await fetch(origin+'/api/finance/payments',{method:'POST',headers:clerk,body:JSON.stringify({patientKey:key,invoiceId:cashierBill.invoice.id,source:'CASH',amount:cashierBill.summary.KHR.balance,currency:'KHR'})});
    assert.equal(response.status,201,await response.text());
    nurseQueue=(await(await fetch(origin+'/api/opd/nurse-paraclinic-orders',{headers:nurse})).json()).orders;
    assert.ok(nurseQueue.some(item=>item.order.id===nurseLab.order.id),'Cashier payment alerts the OPD nurse queue');
    let nurseSend=await nurseAction(nurseLab.order.id,'COLLECT');
    let nurseSendBody=await nurseSend.json();
    assert.equal(nurseSend.status,200,JSON.stringify(nurseSendBody));
    assert.equal(nurseSendBody.stage,'SAMPLE_COLLECTED');
    nurseSend=await nurseAction(nurseLab.order.id,'SEND');
    nurseSendBody=await nurseSend.json();
    assert.equal(nurseSend.status,200,JSON.stringify(nurseSendBody));
    assert.equal(nurseSendBody.cashierPaymentRequired,false);
    assert.equal(nurseSendBody.order.status,'SENT_TO_LAB');
    const latestOrders=(await(await fetch(origin+`/api/paraclinic/orders?patientKey=${encodeURIComponent(key)}`,{headers:doctor})).json()).orders;
    assert.equal(latestOrders.find(item=>item.id===nurseLab.order.id)?.request.opdHandoff.stage,'SENT_TO_DEPARTMENT');
    labList=(await(await fetch(origin+'/api/paraclinic/orders?modality=LAB',{headers:lab})).json()).orders;
    assert.ok(labList.some(item=>item.id===nurseLab.order.id&&item.status==='SENT_TO_LAB'),'Laboratory receives the paid specimen after the nurse sends it');

    const nurseImagingResponse=await fetch(origin+'/api/paraclinic/orders',{method:'POST',headers:doctor,body:JSON.stringify({patientKey:key,modality:'ULTRASOUND',priority:'ROUTINE',chargeMode:'FREE',handoffMode:'NURSE',request:{examination:'Nurse handoff pelvic ultrasound',clinicalIndication:'Workflow test'}})});
    const nurseImaging=await nurseImagingResponse.json();
    assert.equal(nurseImagingResponse.status,201,JSON.stringify(nurseImaging));
    imagingList=(await(await fetch(origin+'/api/paraclinic/orders',{headers:imaging})).json()).orders;
    assert.ok(!imagingList.some(item=>item.id===nurseImaging.order.id),'Imaging is held until the OPD nurse receives the request');
    nurseQueue=(await(await fetch(origin+'/api/opd/nurse-paraclinic-orders',{headers:nurse})).json()).orders;
    assert.ok(nurseQueue.some(item=>item.order.id===nurseImaging.order.id));
    nurseSend=await nurseAction(nurseImaging.order.id,'SEND');
    nurseSendBody=await nurseSend.json();
    assert.equal(nurseSend.status,200,JSON.stringify(nurseSendBody));
    assert.equal(nurseSendBody.stage,'SENT_TO_DEPARTMENT');
    imagingList=(await(await fetch(origin+'/api/paraclinic/orders',{headers:imaging})).json()).orders;
    assert.ok(imagingList.some(item=>item.id===nurseImaging.order.id),'Imaging receives the request after OPD nurse coordination');

    const latestPatient=(await(await fetch(origin+`/api/patient-record?patientKey=${encodeURIComponent(key)}`,{headers:doctor})).json()).patient;
    const prescription=await fetch(origin+'/api/patient-record',{method:'PUT',headers:doctor,body:JSON.stringify({patientKey:key,summary:opdSummary,data:{'system:opdMedications':JSON.stringify([{name:'Test medicine 5mg',route:'po',unit:'គ្រាប់',scheduleType:'bid',doseAmount:'1',m:'1',a:'0',e:'1',n:'0',d:'3',total:'6'}])},expectedVersion:latestPatient.version,editorScope:'medical',submitOpdPrescription:true})});
    assert.equal(prescription.status,200,await prescription.text());
    const afterPrescription=await makeOrder('ULTRASOUND','FREE',{examination:'Prescription queue exclusion ultrasound',clinicalIndication:'Queue exclusion test'},{handoffMode:'NURSE'});
    const afterPrescriptionOrder=await afterPrescription.json();
    assert.equal(afterPrescription.status,201,JSON.stringify(afterPrescriptionOrder));
    nurseQueue=(await(await fetch(origin+'/api/opd/nurse-paraclinic-orders',{headers:nurse})).json()).orders;
    assert.ok(!nurseQueue.some(item=>item.order.id===afterPrescriptionOrder.order.id),'patients with a submitted OPD prescription are excluded from the nurse collection queue');
    const blockedNurseAction=await nurseAction(afterPrescriptionOrder.order.id,'SEND');
    assert.equal(blockedNurseAction.status,409,'the server also blocks nurse handoff after an OPD prescription is submitted');
  } finally {
    await new Promise(resolve=>app.server.close(resolve));
    app.database.close();
  }
});
